#!/usr/bin/env python3
"""Generic repo-local agent swarm control script.

This script intentionally uses only the Python standard library. It expects JSON
manifests generated by the bootstrap skill. Projects may replace it with a
native engine if the same command contracts are preserved.
"""

from __future__ import annotations

import argparse
import datetime as dt
import glob
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path


COMMANDS = [
    "sync-references",
    "collect-context",
    "route",
    "render-prompt",
    "check-report",
    "sync-constraints",
    "check-constraints",
    "new-run",
    "clean-runs",
]


def repo_root() -> Path:
    if os.environ.get("AGENT_SWARM_REPO"):
        return Path(os.environ["AGENT_SWARM_REPO"]).resolve()
    here = Path(__file__).resolve()
    if here.parent.name == "bin" and here.parent.parent.name == ".agents":
        return here.parent.parent.parent.resolve()
    try:
        out = subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True)
        return Path(out.strip()).resolve()
    except Exception:
        return Path.cwd().resolve()


def rel(root: Path, path: Path) -> str:
    try:
        return path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return path.as_posix()


def read_json(path: Path, default):
    if not path.exists():
        return default
    with path.open("r", encoding="utf-8") as f:
        return json.load(f)


def write_json(path: Path, value) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        json.dump(value, f, indent=2, ensure_ascii=False, sort_keys=True)
        f.write("\n")


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def config(root: Path) -> dict:
    base = root / ".agents" / "manifests"
    return {
        "agents": read_json(base / "agents.json", {"agents": {}}),
        "modules": read_json(base / "modules.json", {"modules": {}}),
        "domains": read_json(base / "domains.json", {"domains": {}}),
        "routes": read_json(root / ".agents" / "router" / "routes.json", {"routes": []}),
        "constraints": read_json(base / "constraint-subscriptions.json", {"constraints": {}}),
        "references": read_json(base / "references.json", {"references": []}),
        "retention": read_json(base / "retention.json", {"retention": {"default_days": 14}}),
    }


def split_keywords(text: str) -> list[str]:
    return normalize(re.split(r"[\s,/_:\.\-]+", text.lower()))


def normalize(values: list[str]) -> list[str]:
    seen = set()
    out = []
    for value in values or []:
        value = str(value).strip()
        if value and value not in seen:
            seen.add(value)
            out.append(value)
    return out


def any_prefix(paths: list[str], prefixes: list[str]) -> bool:
    return any(path.startswith(prefix) for path in paths for prefix in prefixes or [])


def any_keyword(words: list[str], candidates: list[str]) -> bool:
    lowered = {str(c).lower() for c in candidates or []}
    return any(word.lower() in lowered for word in words)


def collect_context(summary: str, paths: list[str]) -> dict:
    keywords = split_keywords(summary)
    for path in paths:
        keywords.extend(split_keywords(path))
    return {
        "source": "fallback-static",
        "summary": summary,
        "paths": normalize(paths),
        "symbols": [],
        "keywords": normalize(keywords),
    }


def route_task(root: Path, impact: dict) -> dict:
    cfg = config(root)
    result = {
        "workflow": "classify-and-act",
        "primary_agents": [],
        "reviewer_agents": [],
        "required_references": [],
        "notes": [],
    }
    paths = impact.get("paths", [])
    keywords = impact.get("keywords", [])

    for rule in cfg["routes"].get("routes", []):
        match = rule.get("match", {})
        if any_prefix(paths, match.get("paths", [])) or any_keyword(keywords, match.get("keywords", [])):
            result["primary_agents"].extend(rule.get("primary_agents", []))
            result["reviewer_agents"].extend(rule.get("reviewer_agents", []))
            if rule.get("workflow"):
                result["workflow"] = rule["workflow"]

    for name, item in cfg["modules"].get("modules", {}).items():
        if name in keywords or any_prefix(paths, item.get("paths", [])):
            result["primary_agents"].append(item.get("agent", f"modules/{name}-agent"))

    for name, item in cfg["domains"].get("domains", {}).items():
        if name in keywords or any_prefix(paths, item.get("paths", [])):
            result["primary_agents"].append(item.get("agent", f"domains/{name}-domain-agent"))

    for cid, item in cfg["constraints"].get("constraints", {}).items():
        applies = item.get("applies_to", {})
        if any_prefix(paths, applies.get("paths", [])) or any_keyword(keywords, item.get("keywords", [])):
            result["required_references"].append(cid)

    result["primary_agents"] = sorted(normalize(result["primary_agents"]))
    result["reviewer_agents"] = sorted(normalize(result["reviewer_agents"]))
    result["required_references"] = sorted(normalize(result["required_references"]))
    if len(result["primary_agents"]) > 1 and result["workflow"] == "classify-and-act":
        result["workflow"] = "route-and-synthesize"
    if any_keyword(keywords, ["ws", "websocket", "trace", "consul", "broadcast", "cluster"]):
        result["workflow"] = "adversarial-workflow"
        result["reviewer_agents"] = sorted(normalize(result["reviewer_agents"] + ["reviewers/harness-reviewer-agent"]))
    return result


def cmd_collect_context(root: Path, args: argparse.Namespace) -> int:
    paths = [p for p in args.paths.split(",") if p] if args.paths else []
    print(json.dumps(collect_context(args.summary or "", paths), indent=2, ensure_ascii=False))
    return 0


def cmd_route(root: Path, args: argparse.Namespace) -> int:
    paths = [p for p in args.paths.split(",") if p] if args.paths else []
    impact = collect_context(args.summary or "", paths)
    print(json.dumps(route_task(root, impact), indent=2, ensure_ascii=False))
    return 0


def cmd_render_prompt(root: Path, args: argparse.Namespace) -> int:
    paths = [p for p in args.paths.split(",") if p] if args.paths else []
    route = route_task(root, collect_context(args.summary or "", paths))
    template = Path(args.template)
    if not template.is_absolute():
        template = root / template
    text = template.read_text(encoding="utf-8")
    replacements = {
        "{{workflow}}": route["workflow"],
        "{{primary_agents}}": ", ".join(route["primary_agents"]),
        "{{reviewer_agents}}": ", ".join(route["reviewer_agents"]),
        "{{required_references}}": ", ".join(route["required_references"]),
    }
    for key, value in replacements.items():
        text = text.replace(key, value)
    print(text, end="")
    return 0


def cmd_check_report(root: Path, args: argparse.Namespace) -> int:
    if args.sample:
        print(json.dumps({
            "agent": "sample-agent",
            "status": "needs_review",
            "changed_files": [],
            "evidence": [],
            "unverified": ["sample only"],
            "risks": [],
        }, separators=(",", ":")))
        return 0
    if not args.file:
        raise SystemExit("--file is required unless --sample is used")
    report = read_json(Path(args.file), {})
    required = ["agent", "status", "changed_files", "evidence", "unverified", "risks"]
    missing = [key for key in required if key not in report]
    if missing:
        raise SystemExit("missing report fields: " + ", ".join(missing))
    return 0


def reference_items(root: Path) -> list[tuple[Path, Path]]:
    refs = config(root)["references"].get("references", [])
    items = []
    for ref in refs:
        if ref.get("source") and ref.get("target"):
            items.append((root / ref["source"], root / ref["target"]))
        if ref.get("glob") and ref.get("target_dir"):
            for source in glob.glob(str(root / ref["glob"])):
                items.append((Path(source), root / ref["target_dir"] / Path(source).name))
    return items


def cmd_sync_references(root: Path, args: argparse.Namespace) -> int:
    lock_items = []
    for source, target in reference_items(root):
        entry = {"source": rel(root, source), "target": rel(root, target), "exists": source.exists()}
        if source.exists():
            entry["sha256"] = sha256(source)
            if not args.dry_run:
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copy2(source, target)
        lock_items.append(entry)
    result = {"items": lock_items, "dry_run": args.dry_run}
    if not args.dry_run:
        write_json(root / ".agents" / "references" / "reference-lock.json", result)
    print(json.dumps(result, indent=2, ensure_ascii=False))
    return 0


def managed_section(ids: list[str], constraints: dict) -> str:
    lines = ["<!-- agent-constraints:start -->"]
    if not ids:
        lines.append("- No direct constraint subscriptions for this directory; use Router output.")
    for cid in sorted(ids):
        item = constraints[cid]
        keywords = item.get("keywords", ["constraint"])
        lines.append(f"- [{cid}]({item.get('source', '')}) - {keywords[0] if keywords else 'constraint'}")
    lines.append("<!-- agent-constraints:end -->")
    return "\n".join(lines)


def replace_section(existing: str, section: str) -> str:
    start = "<!-- agent-constraints:start -->"
    end = "<!-- agent-constraints:end -->"
    i = existing.find(start)
    j = existing.find(end)
    if i >= 0 and j >= i:
        j += len(end)
        return existing[:i].rstrip() + "\n" + section + "\n" + existing[j:].lstrip()
    if existing.strip():
        return existing.rstrip() + "\n\n## Required Constraints\n" + section + "\n"
    return "## Required Constraints\n" + section + "\n"


def constraint_targets(root: Path) -> dict[Path, list[str]]:
    constraints = config(root)["constraints"].get("constraints", {})
    targets: dict[Path, list[str]] = {}
    for cid, item in constraints.items():
        if item.get("status") != "active":
            continue
        applies = item.get("applies_to", {})
        for path in applies.get("paths", []):
            if Path(path).suffix:
                continue
            targets.setdefault(root / path / "AGENTS.md", []).append(cid)
    for agents_file in root.glob("**/AGENTS.md"):
        if ".agents/runs" not in rel(root, agents_file):
            targets.setdefault(agents_file, [])
    return targets


def cmd_sync_constraints(root: Path, args: argparse.Namespace) -> int:
    constraints = config(root)["constraints"].get("constraints", {})
    updated = []
    for path, ids in constraint_targets(root).items():
        if not path.exists() and not args.create_missing:
            continue
        section = managed_section(ids, constraints)
        if not args.dry_run:
            path.parent.mkdir(parents=True, exist_ok=True)
            existing = path.read_text(encoding="utf-8") if path.exists() else ""
            path.write_text(replace_section(existing, section), encoding="utf-8")
        updated.append(rel(root, path))
    print(json.dumps({"updated_files": sorted(updated), "dry_run": args.dry_run}, indent=2, ensure_ascii=False))
    return 0


def cmd_check_constraints(root: Path, args: argparse.Namespace) -> int:
    cfg = config(root)
    agents = cfg["agents"].get("agents", {})
    warnings = []
    errors = []
    checked = 0
    for cid, item in cfg["constraints"].get("constraints", {}).items():
        checked += 1
        source = item.get("source")
        if source and not (root / source).exists():
            errors.append(f"{cid}: source not found: {source}")
        if item.get("status") == "deprecated" and not item.get("replaced_by"):
            warnings.append(f"{cid}: deprecated without replaced_by")
        for agent in item.get("applies_to", {}).get("agents", []):
            if agent not in agents:
                errors.append(f"{cid}: unknown agent {agent}")
    print(json.dumps({"checked": checked, "warnings": warnings, "errors": errors}, indent=2, ensure_ascii=False))
    return 1 if errors else 0


def cmd_new_run(root: Path, args: argparse.Namespace) -> int:
    now = dt.datetime.now(dt.timezone.utc).astimezone()
    slug = re.sub(r"[^a-z0-9]+", "-", args.slug.lower()).strip("-") or "agent-run"
    run_id = now.strftime("%Y%m%d-%H%M%S") + "-" + slug
    path = root / ".agents" / "runs" / run_id
    for child in ["prompts", "reports", "evidence"]:
        (path / child).mkdir(parents=True, exist_ok=True)
    meta = {
        "id": run_id,
        "status": "active",
        "created_at": now.isoformat(),
        "updated_at": now.isoformat(),
        "retention": "default",
        "sedimented_to": [],
        "safe_to_delete_after": (now + dt.timedelta(days=14)).date().isoformat(),
    }
    write_json(path / "run-meta.json", meta)
    print(rel(root, path))
    return 0


def cmd_clean_runs(root: Path, args: argparse.Namespace) -> int:
    runs = root / ".agents" / "runs"
    actions = []
    if not runs.exists():
        actions.append("no runs directory")
    else:
        today = dt.date.today()
        for path in sorted(runs.iterdir()):
            if not path.is_dir():
                continue
            meta = read_json(path / "run-meta.json", {})
            safe = meta.get("safe_to_delete_after")
            expired = False
            if safe:
                try:
                    expired = dt.date.fromisoformat(safe) <= today and meta.get("status") != "active"
                except ValueError:
                    pass
            if expired:
                actions.append("delete: " + path.name)
                if args.apply:
                    shutil.rmtree(path)
            else:
                actions.append("keep: " + path.name)
    print(json.dumps({"actions": actions, "apply": args.apply}, indent=2, ensure_ascii=False))
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser()
    sub = parser.add_subparsers(dest="command", required=True)
    p = sub.add_parser("sync-references")
    p.add_argument("--dry-run", action="store_true")
    p.set_defaults(func=cmd_sync_references)
    p = sub.add_parser("collect-context")
    p.add_argument("--summary", default="")
    p.add_argument("--paths", default="")
    p.set_defaults(func=cmd_collect_context)
    p = sub.add_parser("route")
    p.add_argument("--summary", default="")
    p.add_argument("--paths", default="")
    p.set_defaults(func=cmd_route)
    p = sub.add_parser("render-prompt")
    p.add_argument("--summary", default="")
    p.add_argument("--paths", default="")
    p.add_argument("--template", default=".agents/templates/agent-task.md")
    p.set_defaults(func=cmd_render_prompt)
    p = sub.add_parser("check-report")
    p.add_argument("--file", default="")
    p.add_argument("--sample", action="store_true")
    p.set_defaults(func=cmd_check_report)
    p = sub.add_parser("sync-constraints")
    p.add_argument("--dry-run", action="store_true")
    p.add_argument("--create-missing", action="store_true")
    p.set_defaults(func=cmd_sync_constraints)
    p = sub.add_parser("check-constraints")
    p.set_defaults(func=cmd_check_constraints)
    p = sub.add_parser("new-run")
    p.add_argument("--slug", default="agent-run")
    p.set_defaults(func=cmd_new_run)
    p = sub.add_parser("clean-runs")
    p.add_argument("--dry-run", action="store_true")
    p.add_argument("--apply", action="store_true")
    p.set_defaults(func=cmd_clean_runs)
    return parser


def main() -> int:
    args = build_parser().parse_args()
    return args.func(repo_root(), args)


if __name__ == "__main__":
    sys.exit(main())
