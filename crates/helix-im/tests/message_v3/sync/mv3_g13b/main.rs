/// needSync 必须在 channel/member durable 成功后才发 sync，并从 durable cursor=0 起拉取。
#[test]
fn hydration_need_sync_waits_for_sync_then_readback() -> Result<(), String> {
    let mut replay = Replay::new();
    let http_corr = replay.start(CHANNEL)?;
    replay.reply_http(http_corr, INCREMENT_NEEDS_SYNC_BODY_B64)?;
    let persist_corr = replay
        .persist_corr()
        .expect("channel/member persist correlation");
    replay.reply_persist_ok(persist_corr)?;
    assert!(
        replay.events().is_empty(),
        "hydration increment barrier leaked events: {:?}",
        replay.events()
    );
    let sync_corr = replay
        .sync_corr()
        .ok_or_else(|| "needSync must issue sync/notify after durable increment".to_string())?;
    let Effect::Http { req, .. } = replay
        .sink
        .as_slice()
        .iter()
        .find(|effect| matches!(effect, Effect::Http { req, .. } if req.url.ends_with("/channel/sync/notify")))
        .expect("sync effect")
    else {
        unreachable!();
    };
    let body: Value = serde_json::from_slice(req.body.as_ref().expect("sync body"))
        .map_err(|error| error.to_string())?;
    assert_eq!(
        body,
        json!({
            "cursors": [{"channelId": CHANNEL, "fromSeq": 0}]
        })
    );
    replay.reply_http(sync_corr, SYNC_NO_CHANGE_BODY_B64)?;
    assert!(replay.events().is_empty());
    replay.complete_readback()?;
    let events = replay.events();
    assert_eq!(events.len(), 1);
    assert_eq!(events[0]["event"], "im:read:result");
    assert_eq!(events[0]["data"]["body"]["cursor"], 0);
    Ok(())
}

