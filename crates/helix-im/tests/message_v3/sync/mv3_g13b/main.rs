/// 驱动真实 `ImModule::handle`，不旁路 outbound 或 PortReply owner。
struct Replay {
    module: ImModule,
    sink: EffectSink,
}

impl Replay {
    /// 创建带固定 RuntimeAuth 的单频道 hydration 回放器。
    fn new() -> Self {
        Self {
            module: ImModule::new(ImConfig {
                auth_user_id: VIEWER.to_string(),
                company_id: COMPANY.to_string(),
                api_base_url: "http://g13b.invalid/api/cses".to_string(),
                default_api_base_url: "http://g13b.invalid/api/cses".to_string(),
                ..ImConfig::default()
            }),
            sink: EffectSink::new(),
        }
    }

    /// 执行一步并清除上一步的 Effect batch。
    fn step(&mut self, tick: Tick) -> Result<(), String> {
        self.sink.clear();
        self.module
            .handle(&tick, 1_700_001_800_000, &mut self.sink)
            .map_err(|error| error.to_string())
    }

    /// 发起单频道 increment 命令并返回唯一 HTTP correlation。
    fn start(&mut self, channel_id: &str) -> Result<Correlation, String> {
        self.start_with_id(channel_id, "")
    }

    /// 使用独立请求 ID 回放同频道并发加载。
    fn start_with_id(&mut self, channel_id: &str, req_id: &str) -> Result<Correlation, String> {
        self.step(Tick::Command(AppCommand::new(
            "im_channel_load_increment_by_channel_id",
            serde_json::to_vec(&if req_id.is_empty() {
                json!({ "channel_id": channel_id })
            } else {
                json!({ "channel_id": channel_id, "req_id": req_id })
            })
            .map_err(|error| error.to_string())?,
        )))?;
        let http = self
            .sink
            .as_slice()
            .iter()
            .find_map(|effect| match effect {
                Effect::Http { corr, .. } => Some(*corr),
                _ => None,
            })
            .ok_or_else(|| "hydration command must emit one HTTP effect".to_string())?;
        let Effect::Http { req, .. } = self
            .sink
            .as_slice()
            .iter()
            .find(|effect| matches!(effect, Effect::Http { .. }))
            .expect("HTTP effect exists")
        else {
            unreachable!();
        };
        assert_eq!(req.method, "POST");
        assert!(req.url.ends_with("/channel/load/incrementByChannelId"));
        let body: Value = serde_json::from_slice(req.body.as_ref().expect("body"))
            .map_err(|error| error.to_string())?;
        assert_eq!(body, json!({ "channelId": channel_id }));
        Ok(http)
    }

    /// 回灌 ADR-007 HTTP 成功信封。
    fn reply_http(&mut self, corr: Correlation, body_b64: &str) -> Result<(), String> {
        self.step(Tick::PortReply {
            corr,
            outcome: PortOutcome::Ok(ReplyBytes(Bytes::from(
                serde_json::to_vec(&json!({
                    "status": 200,
                    "headers": [],
                    "body": body_b64,
                }))
                .map_err(|error| error.to_string())?,
            ))),
        })
    }

    /// 回灌裸 Go body；sync 与 latest-post 均经过真实 ADR-007 解层。
    fn reply_http_body(&mut self, corr: Correlation, body: Bytes) -> Result<(), String> {
        self.step(Tick::PortReply {
            corr,
            outcome: PortOutcome::Ok(ReplyBytes(common::enveloped(body))),
        })
    }

    /// 返回当前 batch 中的 sync/notify HTTP correlation。
    fn sync_corr(&self) -> Option<Correlation> {
        self.sink.as_slice().iter().find_map(|effect| match effect {
            Effect::Http { corr, req } if req.url.ends_with("/channel/sync/notify") => Some(*corr),
            _ => None,
        })
    }

    /// 返回 TooLong 后 Helix 主动发起的权威 latest-post HTTP correlation。
    fn latest_reload_corr(&self) -> Option<Correlation> {
        self.sink.as_slice().iter().find_map(|effect| match effect {
            Effect::Http { corr, req } if req.url.ends_with("/posts/getLatestPost") => Some(*corr),
            _ => None,
        })
    }

    /// 返回当前 batch 中的持久化 correlation（普通或原子写）。
    fn write_corr(&self) -> Option<Correlation> {
        self.sink.as_slice().iter().find_map(|effect| match effect {
            Effect::Persist { corr, .. } | Effect::PersistAtomic { corr, .. } => Some(*corr),
            _ => None,
        })
    }

    /// 回灌一个持久化成功回执并返回新产生的 effects。
    fn reply_persist_ok(&mut self, corr: Correlation) -> Result<(), String> {
        self.step(Tick::PortReply {
            corr,
            outcome: PortOutcome::Ok(ReplyBytes(Bytes::new())),
        })
    }

    /// 回灌一个本地 Scan/Get rows 回执。
    fn reply_rows(&mut self, corr: Correlation, rows: Value) -> Result<(), String> {
        self.step(Tick::PortReply {
            corr,
            outcome: PortOutcome::Ok(ReplyBytes(Bytes::from(
                serde_json::to_vec(&rows).map_err(|error| error.to_string())?,
            ))),
        })
    }

    /// 回灌一个端口失败回执。
    fn reply_err(&mut self, corr: Correlation) -> Result<(), String> {
        self.step(Tick::PortReply {
            corr,
            outcome: PortOutcome::Err(PortError::Http(502)),
        })
    }

    /// 提取当前 Effect batch 中的 Emit JSON。
    fn events(&self) -> Vec<Value> {
        self.sink
            .as_slice()
            .iter()
            .filter_map(|effect| match effect {
                Effect::Emit { event } => serde_json::from_slice(event.0.as_ref()).ok(),
                _ => None,
            })
            .collect()
    }

    /// 返回当前 batch 的 hydration 原子屏障 correlation。
    fn persist_corr(&self) -> Option<Correlation> {
        self.sink.as_slice().iter().find_map(|effect| match effect {
            Effect::PersistAtomic { corr, .. } => Some(*corr),
            _ => None,
        })
    }

    /// 顺序回放 channel/member/message/cursor 四段 durable read-back。
    fn complete_readback(&mut self) -> Result<(), String> {
        self.complete_readback_with_cursor(0)
    }

    /// 使用指定的 durable cursor 完成 hydration 读回，覆盖 TooLong 提交后的窗口。
    fn complete_readback_with_cursor(&mut self, cursor: i64) -> Result<(), String> {
        for _ in 0..4 {
            let (corr, table) = self
                .sink
                .as_slice()
                .iter()
                .find_map(|effect| match effect {
                    Effect::Persist { corr, ops } => ops.first().map(|op| {
                        let table = match op {
                            helix_core::effect::StorageOp::Get(spec) => spec.table,
                            helix_core::effect::StorageOp::ScopedGet(spec) => spec.table,
                            helix_core::effect::StorageOp::Scan(spec) => spec.table,
                            _ => "",
                        };
                        (*corr, table)
                    }),
                    _ => None,
                })
                .ok_or_else(|| {
                    format!(
                        "expected next hydration read-back Persist; effects={:?}; events={:?}",
                        self.sink.as_slice(),
                        self.events()
                    )
                })?;
            let rows = match table {
                "channel" => json!([{
                    "id": CHANNEL,
                    "display_name": "G13b",
                    "team_id": COMPANY,
                    "user_id": VIEWER,
                    "members": "[]",
                    "unread_count": 3,
                }]),
                "channel_member" => json!([{
                    "channel_id": CHANNEL,
                    "user_id": VIEWER,
                    "team_id": COMPANY,
                    "role": "MEMBER",
                    "unread_count": 3,
                    "unread_post_id": "g13b-anchor", "last_read_seq": 0,
                }]),
                "message" => json!([]),
                "channel_event_cursor" => json!([{
                    "channel_id": CHANNEL,
                    "last_event_seq": cursor,
                }]),
                other => return Err(format!("unexpected hydration read-back table {other}")),
            };
            self.reply_rows(corr, rows)?;
            if !self.events().is_empty() {
                return Ok(());
            }
        }
        Err("hydration read-back did not produce terminal result".to_string())
    }
}

/// HTTP 成功只接收 authority；未过 channel/member durable barrier 前不得提前发布 Result 或业务事件。
#[test]
fn hydration_http_waits_for_channel_member_persist_and_has_no_legacy_emit() -> Result<(), String> {
    let mut replay = Replay::new();
    let http_corr = replay.start(CHANNEL)?;
    replay.reply_http(http_corr, INCREMENT_BODY_B64)?;

    assert!(
        replay.events().is_empty(),
        "HTTP admission must not emit terminal result"
    );
    let persist_corr = replay
        .persist_corr()
        .ok_or_else(|| "increment must persist channel/member before terminal work".to_string())?;
    assert!(replay
        .sink
        .as_slice()
        .iter()
        .all(|effect| { !matches!(effect, Effect::Http { .. } | Effect::Send { .. }) }));

    replay.reply_persist_ok(persist_corr)?;
    assert!(
        replay.events().is_empty(),
        "hydration must not emit channel_hydrated or read result before read-back"
    );
    assert!(replay
        .sink
        .as_slice()
        .iter()
        .all(|effect| { !matches!(effect, Effect::Http { .. } | Effect::Send { .. }) }));
    Ok(())
}

/// increment authority 必须在首个原子屏障写入 viewer 未读绝对态与对应业务水位。
#[test]
fn hydration_increment_persists_viewer_unread_authority_before_history() -> Result<(), String> {
    let mut replay = Replay::new();
    let http_corr = replay.start(CHANNEL)?;
    replay.reply_http(http_corr, INCREMENT_BODY_B64)?;

    // 旧版非 revision 快照经 sequence guard 更新，BatchUpsert 只建复合键种子。
    let projection = replay
        .sink
        .as_slice()
        .iter()
        .find_map(|effect| match effect {
            Effect::PersistAtomic { ops, .. } => ops.iter().find_map(|op| match op {
                StorageOp::ScopedGuardedBump(spec) if spec.table == "channel_member" => Some(spec),
                _ => None,
            }),
            _ => None,
        })
        .ok_or_else(|| "hydration must persist guarded member authority".to_string())?;
    assert_eq!(projection.scope_col, "channel_id");
    assert!(matches!(&projection.scope_val, SqlValue::Text(id) if id == CHANNEL));
    assert_eq!(projection.key_col, "user_id");
    assert!(matches!(&projection.key_val, SqlValue::Text(id) if id == VIEWER));
    assert_eq!(projection.guard_col, "last_unread_event_seq");
    assert_eq!(projection.guard_val, 0);
    let viewer = &projection.set_cols;
    assert!(viewer
        .iter()
        .any(|(name, value)| { name == "unread_count" && matches!(value, SqlValue::Integer(3)) }));
    assert!(viewer.iter().any(|(name, value)| {
        name == "last_unread_event_seq" && matches!(value, SqlValue::Integer(0))
    }));
    Ok(())
}

/// no-sync hydration 必须最终只释放一个 typed Result，不触发 dialog/messages 查询或业务广播。
#[test]
fn hydration_no_sync_releases_one_typed_result_only() -> Result<(), String> {
    let mut replay = Replay::new();
    let http_corr = replay.start(CHANNEL)?;
    replay.reply_http(http_corr, INCREMENT_BODY_B64)?;
    let persist_corr = replay.persist_corr().expect("persist correlation");
    replay.reply_persist_ok(persist_corr)?;
    replay.complete_readback()?;

    let events = replay.events();
    assert_eq!(
        events.len(),
        1,
        "one hydration request must have one terminal Result"
    );
    assert_eq!(events[0]["event"], "im:read:result");
    assert!(events[0]["data"]["req_id"].as_str().is_some());
    assert_eq!(events[0]["data"]["body"]["channelId"], CHANNEL);
    assert_eq!(
        events[0]["data"]["body"]["unreadReconcile"],
        json!({"authority": 3, "local": 3, "status": "match"})
    );
    assert!(replay
        .sink
        .as_slice()
        .iter()
        .all(|effect| { !matches!(effect, Effect::Http { .. } | Effect::Send { .. }) }));
    Ok(())
}

